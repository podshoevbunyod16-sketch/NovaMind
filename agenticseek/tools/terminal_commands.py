def _python_command(args: list[str]):
    """Parse ``python3 -m novamind_cli ...`` into ``(target, payload)``.

    The syntax intentionally accepts a single quoted JSON argument only.  This
    makes shell chaining impossible and gives a failed model call one clear
    structure to repair on its next turn.
    """
    if len(args) < 4 or args[0] not in PYTHON_PROGRAMS or args[1:3] != ["-m", MODULE]:
        return None
    tail = args[3:]
    if tail == ["tools"]:
        return "__tools__", ""
    if tail == ["mcp", "tools"]:
        return "__mcp_tools__", ""
    if len(tail) == 3 and tail[0] == "call":
        target, body = tail[1], tail[2]
        if target in {"terminal", "bash", "python"}:
            raise ValueError("Запускайте код непосредственно командой в terminal.")
        try:
            value = json.loads(body)
        except ValueError as exc:
            raise ValueError(f"Аргументы инструмента должны быть корректным JSON: {exc}") from exc
        if not isinstance(value, dict):
            raise ValueError("Аргументы инструмента должны быть JSON-объектом.")
        return target, body
    if len(tail) == 3 and tail[:2] == ["mcp", "call"]:
        value = json.loads(tail[2])
        if not isinstance(value, dict):
            raise ValueError("MCP ожидает JSON-объект.")
        return "mcp_call", tail[2]
    raise ValueError(
        "Некорректная Python-команда NovaMind. Используйте: "
        "python3 -m novamind_cli call <tool> '<JSON>'; один вызов на блок."
    )


def parse_command(payload: str):
    """Return ``(target, payload)``, None for ordinary shell, or raise.

    Legacy ``nova ...`` commands remain accepted so saved skills and older
    models continue to work, while new prompts exclusively teach the Python
    command gateway.
    """
    text = str(payload or "").strip()
    try:
        args = shlex.split(text)
    except ValueError as exc:
        if text.startswith(("python -m novamind_cli", "python3 -m novamind_cli", "nova ")):
            raise ValueError(f"Некорректные кавычки команды: {exc}") from exc
        return None

    python_call = _python_command(args)
    if python_call is not None:
        return python_call
    if not text.startswith("nova "):
        return None
    if args == ["nova", "tools"]:
        return "__tools__", ""
    if args == ["nova", "mcp", "tools"]:
        return "__mcp_tools__", ""
    if len(args) == 4 and args[:2] == ["nova", "call"]:
        if args[2] in {"terminal", "bash", "python"}:
            raise ValueError("Запускайте код непосредственно блоком python или terminal.")
        return args[2], args[3]
    if len(args) == 4 and args[:3] == ["nova", "web", "search"]:
        return "web_search", args[3]
    if len(args) == 4 and args[:3] == ["nova", "web", "open"]:
        return "web_open", args[3]
    if len(args) == 4 and args[:3] == ["nova", "mcp", "call"]:
        value = json.loads(args[3])
        if not isinstance(value, dict):
            raise ValueError("MCP ожидает JSON-объект.")
        return "mcp_call", args[3]
    # Preserve the ordinary terminal's built-in nova search/read/help commands.
    if len(args) > 1 and args[1] in {"search", "read", "help"}:
        return None
    raise ValueError("Некорректная nova-команда. Используйте Python gateway; один вызов на блок.")


def _delegated_input(target: str, body: str) -> tuple[str, str | None]:
    """Translate gateway JSON into the legacy payload expected by a tool.

    AgenticSeek tools predate the JSON CLI: web tools expect a bare string and
    ``file_write`` expects content plus a save path.  Without this adapter a
    perfectly valid command searched literally for ``{\"query\": ...}`` and
    file creation always failed.  Other tools already consume JSON directly.
    """
    data = json.loads(body)
    if target == "web_search":
        query = str(data.get("query") or data.get("q") or "").strip()
        if not query:
            raise ValueError("web_search: нужен query")
        try:
            limit = int(data.get("limit") or 0)
        except (TypeError, ValueError):
            limit = 0
        return (f"{query}\nlimit={limit}" if limit > 0 else query), None
    if target == "web_open":
        url = str(data.get("url") or data.get("href") or "").strip()
        if not url:
            raise ValueError("web_open: нужен url")
        return url, None
    if target in {"file_find", "file_finder"}:
        name = str(data.get("name") or data.get("path") or data.get("file") or "").strip()
        if not name:
            raise ValueError("file_find: нужен name или path")
        action = str(data.get("action") or "find").strip()
        return f"action={action}\nname={name}", None
    if target == "file_write":
        path = str(data.get("path") or data.get("name") or data.get("file") or "").strip()
        if not path:
            raise ValueError("file_write: нужен path")
        if "content" not in data:
            raise ValueError("file_write: нужен content")
        return str(data.get("content") or ""), path
    return body, None


def _catalog_step(agent, payload: str, feedback: str):
    """Show catalog lookup as an actually completed terminal step."""
    from agenticseek.timeline import tool_event

    emit = getattr(agent, "emit", None)
    if callable(emit):
        try:
            emit(tool_event("terminal", str(payload).strip(), ok=True,
                            command=str(payload).strip(), output=feedback, code=0))
        except Exception:  # noqa: BLE001 — rendering must not break execution
            pass
    state = getattr(agent, "state", None)
    if state is not None and hasattr(state, "add_tool"):
        try:
            state.add_tool("terminal", True)
        except Exception:  # noqa: BLE001
            pass


def dispatch(agent, payload: str):
    """Return delegated ``run_tool`` result, or None for the shell sandbox."""
    try:
        parsed = parse_command(payload)
    except (ValueError, TypeError, json.JSONDecodeError) as exc:
        return False, (f"[failure] {exc} Исправь структуру команды/JSON и попробуй "
                       "новой Python-командой; не повторяй этот вызов дословно.")
    if parsed is None:
        return None
    target, body = parsed
    tools = agent.all_tools()
    if target == "__tools__":
        agent.take_step()
        catalog = {getattr(t, "tag", name): t.description for name, t in tools.items()}
        feedback = "[success] " + json.dumps(catalog, ensure_ascii=False)
        _catalog_step(agent, payload, feedback)
        return True, feedback
    if target == "__mcp_tools__":
        agent.take_step()
        tool = tools.get("mcp_call")
        if tool is None:
            return False, "[failure] MCP не подключён для этого исполнителя."
        feedback = "[success] " + tool.description
        _catalog_step(agent, payload, feedback)
        return True, feedback
    if target not in tools:
        return False, (f"[failure] Инструмент {target} недоступен для этого исполнителя. "
                       f"Сначала вызови python3 -m {MODULE} tools и выбери имя из каталога.")

    # The target still executes in its normal policy path.  This marker only
    # changes what the timeline displays: users see the exact generated Python
    # command rather than a synthetic JSON animation.
    try:
        if str(payload).lstrip().startswith(("python -m novamind_cli",
                                            "python3 -m novamind_cli")):
            delegated_body, save_path = _delegated_input(target, body)
        else:  # legacy `nova call/web` payloads keep their historical format
            delegated_body, save_path = body, None
    except (ValueError, TypeError) as exc:
        return False, (f"[failure] {exc}. Исправь JSON и вызови новую Python-команду; "
                       "не повторяй неудачный запрос дословно.")

    previous = getattr(agent, "_gateway_command", "")
    agent._gateway_command = str(payload).strip()
    try:
        if save_path is None:
            ok, feedback = agent.run_tool(target, delegated_body)
        else:
            ok, feedback = agent.run_tool(target, delegated_body, save_path)
    finally:
        agent._gateway_command = previous
    if (not ok and str(feedback).lstrip().startswith("[failure]")
            and "не повторяй" not in str(feedback).lower()):
        feedback = (str(feedback).rstrip()
                    + "\nИсправь структуру запроса по тексту ошибки и вызови новую Python-команду; "
                      "не повторяй неудачный JSON дословно.")
    return ok, feedback
